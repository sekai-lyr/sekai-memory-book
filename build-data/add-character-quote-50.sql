INSERT INTO sekai_memory_book_character_favorite
    (user_id, anime_id, character_name, reason, favorite_level)
SELECT user_id, anime_id, character_name, reason, favorite_level
FROM seed_characters seed
WHERE NOT EXISTS (
    SELECT 1
    FROM sekai_memory_book_character_favorite existing
    WHERE existing.user_id = seed.user_id
      AND existing.anime_id = seed.anime_id
      AND existing.character_name = seed.character_name
);

